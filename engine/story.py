def _quote(text, who, source):
    return {"text": text, "who": who, "source": source}


def risky(amount):
    return lambda s: s.add("risk", amount)


def voice(n):
    return lambda s: s.add("voice", n)


def org(name):
    return lambda s: s.set("org", name)


def flag(name, value=True):
    return lambda s: s.set(name, value)


def both(*fns):
    def run(s):
        for fn in fns:
            if fn:
                fn(s)
    return run


def pressure(node_id, condition, fallback):
    """Route into a pressure scene when the condition holds, otherwise go on."""
    return lambda s: node_id if condition(s) else fallback


def in_russia(s):
    return not s.data["left"] and not s.data["arrested"]


