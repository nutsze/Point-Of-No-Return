def compute_ending(state) -> str:
    d = state.data
    v = d["voice"]
    if d["betrayed"] and d["arrested"] and d["risk"] >= 9:
        return "tragic"
    if d["arrested"]:
        return "win_prison"
    if d["left"]:
        return "win_return" if (d["org"] == "diaspora" and v >= 6) else "emigration"
    if v >= 9 or (v >= 6 and d["org"] is not None):
        return "win"
    return "quiet"


