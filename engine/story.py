def _quote(text, who, source):
    return {"text": text, "who": who, "source": source}


def risky(amount):
    return lambda s: s.add("risk", amount)


def both(*fns):
    def run(s):
        for fn in fns:
            fn(s)
    return run


def voice(n):
    return lambda s: s.add("voice", n)


def org(name):
    return lambda s: s.set("org", name)


