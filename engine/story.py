DEDICATION = [p["name"] + (" †" if p["died"] else "") for p in PEOPLE]


def compute_ending(state):
    d = state.data
    if d["betrayed"] and d["voice"] >= 4:
        return "tragic"
    if d["left"] and not d["joined"]:
        return "emigration"
    if d["voice"] <= 2 and not d["joined"]:
        return "quiet"
    return "win"


